def list_provider_capabilities() -> list[dict[str, Any]]:
    return copy.deepcopy(_CAPABILITY_REGISTRY)


def summarize_provider_capabilities(capabilities: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    rows = capabilities if capabilities is not None else list_provider_capabilities()
    stability_counts = Counter(str(item.get("stability", "")) for item in rows)
    side_effect_counts = Counter(str(item.get("side_effect_level", "")) for item in rows)
    domain_counts = Counter(str(item.get("domain", "")) for item in rows)
    return {
        "total": len(rows),
        "by_domain": {key: domain_counts[key] for key in sorted(domain_counts)},
        "by_stability": {key: stability_counts[key] for key in STABILITY_LEVELS if stability_counts[key]},
        "by_side_effect_level": {key: side_effect_counts[key] for key in SIDE_EFFECT_LEVELS if side_effect_counts[key]},
    }


def build_capability_discovery_payload() -> dict[str, Any]:
    capabilities = list_provider_capabilities()
    return {
        "capabilities": capabilities,
        "summary": summarize_provider_capabilities(capabilities),
        "grading": {
            "stability_levels": list(STABILITY_LEVELS),
            "side_effect_levels": list(SIDE_EFFECT_LEVELS),
        },
    }
