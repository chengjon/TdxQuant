STABILITY_LEVELS = ("stable", "beta", "experimental")
SIDE_EFFECT_LEVELS = ("read_only", "local_state_mutating", "live_side_effecting")


def _capability(
    name: str,
    *,
    domain: str,
    description: str,
    stability: str,
    side_effect_level: str,
    manager_method: str | None = None,
    api_command: str | None = None,
    flat_command: str | None = None,
    requires: list[str] | None = None,
    capability_version: str = "v1",
) -> dict[str, Any]:
    entrypoints: dict[str, str] = {}
    if manager_method:
        entrypoints["manager_method"] = manager_method
    if api_command:
        entrypoints["api_command"] = api_command
    if flat_command:
        entrypoints["flat_command"] = flat_command
    payload = {
        "name": name,
        "capability_version": capability_version,
        "domain": domain,
        "description": description,
        "stability": stability,
        "side_effect_level": side_effect_level,
        "entrypoints": entrypoints,
        "requires": list(requires or []),
    }
    query_metadata = get_query_discovery_metadata(name)
    if query_metadata is not None:
        payload["query_metadata"] = query_metadata
    return payload


